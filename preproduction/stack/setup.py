"""Run the tracking half of the open filmmaking stack (Kitsu + AYON) locally.

  python stack/setup.py build          build native AYON images from release sources (Apple Silicon)
  python stack/setup.py up             start Kitsu and AYON, install AYON's core + Kitsu addons,
                                       point AYON at Kitsu and start the Kitsu -> AYON sync
  python stack/setup.py pair "Film"    pair a Kitsu production with a new AYON project and sync it
  python stack/setup.py status         what's running, URLs and logins
  python stack/setup.py down [--wipe]  stop (and with --wipe, delete all stack data)

Logins are generated on the first `up` and kept in stack/.env (not committed). Kitsu keeps the
cgwire image's default admin (admin@example.com / mysecretpassword); change it in Kitsu.
"""

from __future__ import annotations

import argparse
import json
import re
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

STACK = Path(__file__).resolve().parent
VENDOR = STACK.parent / "vendor"
ENV_FILE = STACK / ".env"
TEMPLATE = STACK / "ayon" / "template.json"

AYON_VERSION = "1.17.8"
CORE_VERSION = "1.10.9"
KITSU_ADDON_VERSION = "1.2.8"
ADDON_URLS = {
    "core": f"https://github.com/ynput/ayon-core/releases/download/{CORE_VERSION}/core-{CORE_VERSION}.zip",
    "kitsu": f"https://github.com/ynput/ayon-kitsu/releases/download/{KITSU_ADDON_VERSION}/kitsu-{KITSU_ADDON_VERSION}.zip",
}
KITSU_DEFAULT_LOGIN = ("admin@example.com", "mysecretpassword")  # created by the cgwire image


# -- small helpers ------------------------------------------------------------------------------


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    print("+", " ".join(cmd))
    return subprocess.run(cmd, check=True, **kw)


def compose(*args: str, **kw) -> subprocess.CompletedProcess:
    return run(["docker", "compose", "-f", str(STACK / "compose.yml"), "--env-file", str(ENV_FILE), *args], **kw)


def load_env() -> dict[str, str]:
    env = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                env[key.strip()] = value.strip()
    return env


def ensure_env() -> dict[str, str]:
    env = load_env()
    defaults = {
        "KITSU_PORT": "8080",
        "AYON_PORT": "5005",
        "AYON_ADMIN_PASSWORD": secrets.token_urlsafe(12),
        "AYON_API_KEY": secrets.token_hex(24),
        "KITSU_EMAIL": KITSU_DEFAULT_LOGIN[0],
        "KITSU_PASSWORD": KITSU_DEFAULT_LOGIN[1],
    }
    changed = False
    for key, value in defaults.items():
        if key not in env:
            env[key] = value
            changed = True
    if changed:
        lines = ["# Local logins for the HelloWorld stack. Generated by stack/setup.py; keep it private."]
        lines += [f"{k}={v}" for k, v in env.items()]
        ENV_FILE.write_text("\n".join(lines) + "\n")
        ENV_FILE.chmod(0o600)
    return env


def write_template(env: dict[str, str]) -> None:
    """AYON reads /template.json on its first start: users, secrets and the addons to install."""
    TEMPLATE.parent.mkdir(parents=True, exist_ok=True)
    template = {
        "users": [
            {"name": "admin", "password": env["AYON_ADMIN_PASSWORD"], "fullName": "AYON admin", "isAdmin": True},
            {"name": "service", "apiKey": env["AYON_API_KEY"], "isService": True},
        ],
        "secrets": {"kitsu_email": env["KITSU_EMAIL"], "kitsu_password": env["KITSU_PASSWORD"]},
        "initialBundle": {
            "name": "helloworld",
            "addons": [{"name": n, "version": u.rsplit("-", 1)[1][:-4], "url": u} for n, u in ADDON_URLS.items()],
        },
    }
    TEMPLATE.write_text(json.dumps(template, indent=2) + "\n")
    TEMPLATE.chmod(0o600)


def http(method: str, url: str, body=None, headers: dict | None = None, timeout: float = 30):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers={"Content-Type": "application/json", **(headers or {})})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        raw = resp.read()
        return json.loads(raw) if raw and resp.headers.get_content_type() == "application/json" else None


def wait_for(what: str, check, timeout: float = 600, every: float = 3):
    start = time.monotonic()
    print(f"waiting for {what} ...", end="", flush=True)
    last_error = None
    while time.monotonic() - start < timeout:
        try:
            result = check()
            if result:
                print(f" ready ({time.monotonic() - start:.0f}s)")
                return result
        except Exception as exc:  # not up yet
            last_error = exc
        print(".", end="", flush=True)
        time.sleep(every)
    print()
    raise SystemExit(f"timed out waiting for {what}: {last_error}")


class Ayon:
    def __init__(self, env: dict[str, str]):
        self.url = f"http://localhost:{env['AYON_PORT']}"
        self.env = env
        self.token = None

    def login(self):
        res = http("POST", f"{self.url}/api/auth/login", {"name": "admin", "password": self.env["AYON_ADMIN_PASSWORD"]})
        self.token = res["token"]

    def call(self, method: str, path: str, body=None):
        if self.token is None:
            self.login()
        return http(method, f"{self.url}{path}", body, {"Authorization": f"Bearer {self.token}"})


# -- commands -----------------------------------------------------------------------------------


def _clone(repo: str, tag: str, dest: Path) -> None:
    if dest.exists():
        current = subprocess.run(["git", "-C", str(dest), "describe", "--tags"], capture_output=True, text=True).stdout.strip()
        if current == tag:
            return
        raise SystemExit(f"{dest} exists at {current or 'an unknown version'}; remove it to build {tag}")
    run(["git", "-c", "advice.detachedHead=false", "clone", "-q", "--depth", "1", "--branch", tag, f"https://github.com/ynput/{repo}.git", str(dest)])


def cmd_build(args) -> None:
    """Native images built from the same release tags as Ynput's published (x86-only) images."""
    docker_dir = VENDOR / "ayon-docker"
    if not docker_dir.exists():
        run(["git", "clone", "-q", "--depth", "1", "https://github.com/ynput/ayon-docker.git", str(docker_dir)])
    _clone("ayon-backend", AYON_VERSION, docker_dir / "backend")
    _clone("ayon-frontend", AYON_VERSION, docker_dir / "frontend")
    (docker_dir / "RELEASE").write_text(
        f"version={AYON_VERSION}\nbuild_date={time.strftime('%Y%m%d')}\nbuild_time={time.strftime('%H%M')}\n"
        f"frontend_branch={AYON_VERSION}\nbackend_branch={AYON_VERSION}\n"
    )
    run(["docker", "build", "-t", f"helloworld/ayon-server:{AYON_VERSION}", str(docker_dir)])

    kitsu_dir = VENDOR / f"ayon-kitsu-{KITSU_ADDON_VERSION}"
    _clone("ayon-kitsu", KITSU_ADDON_VERSION, kitsu_dir)
    processor = kitsu_dir / "services" / "processor"
    run(["docker", "build", "-t", f"helloworld/ayon-kitsu-processor:{KITSU_ADDON_VERSION}", str(processor)])


def cmd_up(args) -> None:
    env = ensure_env()
    write_template(env)
    compose("up", "-d", "kitsu", "postgres", "redis", "ayon")

    kitsu = f"http://localhost:{env['KITSU_PORT']}"
    wait_for("Kitsu", lambda: http("GET", f"{kitsu}/api", timeout=5))
    ayon = Ayon(env)
    wait_for("AYON", lambda: http("GET", f"{ayon.url}/api/info", timeout=5))

    def addons_ready():
        ayon.token = None
        items = ayon.call("GET", "/api/addons")["addons"]
        have = {a["name"]: set(a.get("versions", {})) for a in items}
        return KITSU_ADDON_VERSION in have.get("kitsu", set()) and CORE_VERSION in have.get("core", set())

    wait_for(f"AYON addons (core {CORE_VERSION}, kitsu {KITSU_ADDON_VERSION})", addons_ready, timeout=900, every=5)
    settings_path = f"/api/addons/kitsu/{KITSU_ADDON_VERSION}/settings"
    settings = ayon.call("GET", settings_path)  # the POST replaces the whole document
    settings["server"] = "http://kitsu"
    ayon.call("POST", settings_path, settings)
    print("AYON's Kitsu addon now points at http://kitsu (the Kitsu container)")
    compose("--profile", "sync", "up", "-d", "kitsu-processor")
    cmd_status(args)


def cmd_pair(args) -> None:
    import gazu

    env = load_env()
    if not env:
        raise SystemExit("Run `python stack/setup.py up` first.")
    gazu.set_host(f"http://localhost:{env['KITSU_PORT']}/api")
    gazu.log_in(env["KITSU_EMAIL"], env["KITSU_PASSWORD"])
    project = gazu.project.get_project_by_name(args.kitsu_project)
    if project is None:
        raise SystemExit(f"No Kitsu production named {args.kitsu_project!r}")

    name = args.ayon_project or re.sub(r"[^A-Za-z0-9_]+", "_", args.kitsu_project).strip("_")
    code = args.code or re.sub(r"[^a-z0-9]", "", name.lower())[:8] or "proj"
    ayon = Ayon(env)
    base = f"/api/addons/kitsu/{KITSU_ADDON_VERSION}"
    pairings = ayon.call("GET", f"{base}/pairing") or []
    paired = next((p for p in pairings if p.get("kitsuProjectId") == project["id"] and p.get("ayonProjectName")), None)
    if paired:
        name = paired["ayonProjectName"]
        print(f"Kitsu {args.kitsu_project!r} is already paired with AYON project {name}")
    else:
        ayon.call("POST", f"{base}/pairing", {"kitsuProjectId": project["id"], "ayonProjectName": name, "ayonProjectCode": code})
        print(f"paired Kitsu {args.kitsu_project!r} with new AYON project {name} ({code})")
    ayon.call("POST", f"{base}/sync/{name}")
    print("sync requested; the kitsu-processor service is copying sequences, shots and tasks ...")

    def synced():
        tree = ayon.call("GET", f"/api/projects/{name}/hierarchy")
        folders = tree.get("hierarchy", [])
        count = 0
        stack = list(folders)
        while stack:
            node = stack.pop()
            count += 1
            stack.extend(node.get("children", []))
        return count if count else None

    count = wait_for(f"folders in AYON project {name}", synced, timeout=300, every=5)
    print(f"AYON project {name} has {count} folders: {ayon.url}/projects/{name}/overview")


def cmd_status(args) -> None:
    env = load_env()
    subprocess.run(["docker", "compose", "-f", str(STACK / "compose.yml"), "--env-file", str(ENV_FILE), "--profile", "sync", "ps",
                    "--format", "table {{.Service}}\t{{.State}}\t{{.Status}}"])
    if env:
        print(f"\nKitsu  http://localhost:{env['KITSU_PORT']}   login {env['KITSU_EMAIL']} (password in stack/.env)")
        print(f"AYON   http://localhost:{env['AYON_PORT']}   login admin (password in stack/.env)")
        print("\nFor the helloworld CLI:")
        print(f"  export KITSU_HOST=http://localhost:{env['KITSU_PORT']} KITSU_EMAIL={env['KITSU_EMAIL']}")
        print("  export KITSU_PASSWORD=...   # from stack/.env")


def cmd_down(args) -> None:
    cmd = ["--profile", "sync", "down"]
    if args.wipe:
        cmd.append("--volumes")
    compose(*cmd)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build").set_defaults(func=cmd_build)
    sub.add_parser("up").set_defaults(func=cmd_up)
    p = sub.add_parser("pair")
    p.add_argument("kitsu_project")
    p.add_argument("--ayon-project", help="AYON project name (letters, digits, _)")
    p.add_argument("--code", help="AYON project code")
    p.set_defaults(func=cmd_pair)
    sub.add_parser("status").set_defaults(func=cmd_status)
    p = sub.add_parser("down")
    p.add_argument("--wipe", action="store_true", help="also delete the Kitsu and AYON data volumes")
    p.set_defaults(func=cmd_down)
    args = parser.parse_args()
    try:
        args.func(args)
    except urllib.error.HTTPError as exc:
        raise SystemExit(f"{exc.code} {exc.reason} from {exc.url}: {exc.read().decode(errors='replace')[:400]}")


if __name__ == "__main__":
    main()
